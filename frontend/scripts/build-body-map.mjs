// Turns the Figma export (src/assets/body-map.svg) into bodyMapPaths.ts.
// Usage: node scripts/build-body-map.mjs
// Top-level layers inside <g id="body"> named like a muscle group become
// click targets; every other layer (head, palms, feet...) is decoration.
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "src/assets/body-map.svg";
const TARGET = "src/features/catalog/components/bodyMapPaths.ts";
const MUSCLE_GROUPS = [
  "chest",
  "back",
  "shoulders",
  "arms",
  "core",
  "glutes",
  "thighs",
  "calves",
];

const svg = readFileSync(SOURCE, "utf8");
const viewBox = svg.match(/viewBox="([^"]+)"/)[1];

// Split the markup into top-level layers of <g id="body"> by tracking <g> depth.
const layers = new Map();
let depth = 0;
let current = null;
for (const tag of svg.matchAll(/<(\/?)(g|path)\b([^>]*?)(\/?)>/g)) {
  const [, closing, name, attrs, selfClosing] = tag;
  if (name === "g" && !closing) {
    depth += 1;
    if (depth === 2) {
      current = attrs.match(/id="([^"]+)"/)[1];
      layers.set(current, []);
    }
  } else if (name === "g" && closing) {
    if (depth === 2) current = null;
    depth -= 1;
  } else if (name === "path" && current && (selfClosing || !closing)) {
    layers.get(current).push(attrs.match(/\sd="([^"]+)"/)[1]);
  }
}

const unknown = [...layers.keys()].filter((id) => !MUSCLE_GROUPS.includes(id));
const missing = MUSCLE_GROUPS.filter((group) => !layers.has(group));
if (missing.length > 0)
  throw new Error(`Missing layers: ${missing.join(", ")}`);

const list = (paths) => paths.map((d) => `    "${d}",`).join("\n");
const out = `// Generated by scripts/build-body-map.mjs from ${SOURCE} - do not edit by hand.
import type { MuscleGroup } from "../types";

export const BODY_MAP_VIEWBOX = "${viewBox}";

/** Muscle shapes per group; a group can appear in both views. */
export const MUSCLE_PATHS: Record<MuscleGroup, string[]> = {
${MUSCLE_GROUPS.map((group) => `  ${group}: [\n${list(layers.get(group))}\n  ],`).join("\n")}
};

/** Non-interactive shapes: ${unknown.join(", ")}. */
export const DECOR_PATHS: string[] = [
${unknown
  .flatMap((id) => layers.get(id))
  .map((d) => `  "${d}",`)
  .join("\n")}
];
`;
writeFileSync(TARGET, out);
console.log(
  `${TARGET}: ${MUSCLE_GROUPS.map((g) => `${g} ${layers.get(g).length}`).join(", ")}; decor ${unknown.join("+")}`,
);